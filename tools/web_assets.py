# PlatformIO pre-script: turns the web pages in src/web/ into byte arrays for
# src/web.cpp. The HTML is gzipped (~65 % smaller, served with
# "Content-Encoding: gzip"), the icon is a PNG and stays as it is. The
# header lands in the build directory and is only rewritten when it changes,
# so web.cpp isn't rebuilt every time.
#   src/web/index.html  -> WEB_PAGE_GZ        settings page at "/"
#   src/web/event.html  -> WEB_EVENT_PAGE_GZ  event page at "/event"
#   src/web/icon.png    -> WEB_ICON_PNG       favicon and iOS home-screen icon
import gzip
import os

Import("env")

ASSETS = [
    ("index.html", "WEB_PAGE_GZ", True),
    ("event.html", "WEB_EVENT_PAGE_GZ", True),
    ("icon.png", "WEB_ICON_PNG", False),
]

src_dir = os.path.join(env["PROJECT_DIR"], "src", "web")
out_dir = os.path.join(env.subst("$BUILD_DIR"), "web_assets")
out = os.path.join(out_dir, "web_assets.h")

lines = ["#pragma once", "// Generated by tools/web_assets.py from src/web/, don't edit.",
         "#include <pgmspace.h>", "#include <stdint.h>", ""]
for name, var, compress in ASSETS:
    with open(os.path.join(src_dir, name), "rb") as f:
        data = f.read()
    if compress:
        data = gzip.compress(data, compresslevel=9, mtime=0)  # mtime 0: same input, same bytes
    lines.append("static const uint8_t %s[] PROGMEM = {" % var)
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
text = "\n".join(lines)

os.makedirs(out_dir, exist_ok=True)
old = None
if os.path.exists(out):
    with open(out) as f:
        old = f.read()
if old != text:
    with open(out, "w") as f:
        f.write(text)
env.Append(CPPPATH=[out_dir])
